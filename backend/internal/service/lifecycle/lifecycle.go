// Package lifecycle 是「配置变了」之后的唯一后置管线。
//
// 为什么需要它：同一次配置变更会同时影响两件事——定价快照（谁在售、按什么价）
// 与路由（绑定的渠道还能不能用）。这两件事过去由各 handler 各自记着刷，
// 结果就是有的刷、有的忘：
//
//   - 模型保存会重算文档，但不刷定价缓存；
//   - 渠道启停什么都不刷 —— 于是一个绑到停用渠道的模型在门户里显示「可用」，
//     直到用户调用拿到 503。
//
// **文档不再进这条管线**：文档是内置契约（`apidoc.FamilyDocs()` + `apidoc.SeedDocs()`），
// 与模型上架/启用完全解耦 —— 新增一个模型不会多出一篇文档，下架一个模型也不会
// 少一篇。曾经在这里跑的两步（补族节点、重算协议篇成员）已随成员表一起删除。
//
// 定价失效必须在事务提交之后执行：广播与外部可见性不可回滚。
package lifecycle

import (
	"lingdong-api/internal/service/pricing"
)

// AfterChange 在配置变更（模型/绑定/渠道/规格）提交之后调用。
//
// 无返回值：这条管线只剩「失效定价缓存」一步，它不会失败（只清内存与广播）。
// 曾经它返回 error 供调用方观测「文档重算失败」—— 文档改为内置契约后，
// 那个失败态已经不存在了，保留返回值只会留下三个永远不进的错误分支。
func AfterChange() {
	// 定价快照失效：下一次 Get() 重建（含 OnSaleModels 的在售集合）。
	// 文档里的「适用模型」也在下一次投影时读到新集合，不需要额外动作。
	pricing.InvalidatePricingCache()
}
